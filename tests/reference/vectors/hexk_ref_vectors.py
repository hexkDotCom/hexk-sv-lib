"""Expected values of the packet store of the reference testbench, computed without the library.

    python3 tests/reference/vectors/hexk_ref_vectors.py      (prints the include)
    make reference_vectors                                    (writes it, formatted as the repository holds it)

The CRC comes from zlib; the LFSR and the SECDED code are written here from the description at
the top of hexk_ref_dut.sv. The output is a SystemVerilog include with the fixed vectors that
hexk_ref_vectors_test sends and checks, so that the DUT and the library models of the testbench
are both measured against a third, independent implementation.
"""
import zlib

LFSR_TAPS = 0xB400
LFSR_SEED = 0xACE1


def lfsr_step(state):
    """One step of the 16-bit Galois LFSR: shift right; XOR the taps in when a 1 was shifted out."""
    out = state & 1
    state >>= 1
    return state ^ LFSR_TAPS if out else state


def ecc_encode(data):
    """39-bit SECDED code word of 32 data bits: P at 0, check bits at powers of two, data between."""
    code = [0] * 39
    data_bit = 0
    for pos in range(1, 39):
        if pos & (pos - 1):
            code[pos] = (data >> data_bit) & 1
            data_bit += 1
    for check in range(6):
        parity = 0
        for pos in range(1, 39):
            if pos & (pos - 1) and pos >> check & 1:
                parity ^= code[pos]
        code[1 << check] = parity
    code[0] = sum(code[1:]) & 1
    return sum(bit << pos for pos, bit in enumerate(code))


def packet(words, scramble):
    """CRC of the packet and the stored words (scrambled when asked)."""
    raw = b"".join(word.to_bytes(4, "little") for word in words)
    crc = zlib.crc32(raw) & 0xFFFFFFFF
    stored = []
    state = LFSR_SEED
    for word in words:
        state = lfsr_step(state)
        stored.append(word ^ (state << 16 | state) if scramble else word)
    return crc, stored


PACKETS = [
    # (words, scramble, base)
    ([0x00000000], 0, 0),
    ([0x12345678, 0x9ABCDEF0, 0x0F1E2D3C, 0x4B5A6978], 0, 8),
    ([0x12345678, 0x9ABCDEF0, 0x0F1E2D3C, 0x4B5A6978], 1, 16),
    ([0xFFFFFFFF, 0x00000001, 0x80000000, 0xDEADBEEF, 0xCAFEF00D, 0x01234567, 0x89ABCDEF], 1, 60),
]


def main():
    print("// SPDX-License-Identifier: Apache-2.0")
    print("// Copyright (c) 2026 HEXK")
    print("//")
    print("// hexk_ref_vectors.svh")
    print("//")
    print("// Generated by hexk_ref_vectors.py; do not edit.")
    print("// Fixed packets with their CRC, stored words and code words, computed without the library.")
    print()
    print("`ifndef HEXK_REF_VECTORS_SVH")
    print("`define HEXK_REF_VECTORS_SVH")
    print()
    print(f"localparam int unsigned HEXK_REF_NUM_VECTORS = {len(PACKETS)};")
    print()
    print("// One fixed packet: its words, mode and base, and what the DUT must hold afterwards.")
    print("typedef struct {")
    print("   bit [31:0] words  [$];")
    print("   bit        scramble;")
    print("   bit [ 5:0] base;")
    print("   bit [31:0] crc;")
    print("   bit [31:0] stored [$];")
    print("   bit [38:0] codes  [$];")
    print("} hexk_ref_vector_t;")
    print()
    print("// The fixed packets.")
    print("function automatic hexk_ref_vector_t hexk_ref_vector(int unsigned index);")
    print("   hexk_ref_vector_t vector;")
    print("   case (index)")
    for index, (words, scramble, base) in enumerate(PACKETS):
        crc, stored = packet(words, scramble)
        print(f"      {index}: begin")
        print("         vector.words  = {" + ", ".join(f"32'h{w:08X}" for w in words) + "};")
        print(f"         vector.scramble = 1'b{scramble};")
        print(f"         vector.base   = 6'd{base};")
        print(f"         vector.crc    = 32'h{crc:08X};")
        print("         vector.stored = {" + ", ".join(f"32'h{w:08X}" for w in stored) + "};")
        print("         vector.codes  = {" + ", ".join(f"39'h{ecc_encode(w):010X}" for w in stored) + "};")
        print("      end")
    print("      default: ;")
    print("   endcase")
    print("   return vector;")
    print("endfunction : hexk_ref_vector")
    print()
    print("`endif  // HEXK_REF_VECTORS_SVH")


if __name__ == "__main__":
    main()
